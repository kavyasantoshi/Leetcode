class Solution {
public:
    long long countCommas(long long n) {
        string s = to_string(n);
        long long k = s.size();
        if (k <= 3)
            return 0;
        else if ((k-1) / 3 == 2)
            return 2 * (n - 999999) + 1 * (999999 - 999);
        else if((k-1)/3 ==3) return 3*(n-999999999)+2*(1000000000-1000000)+1*(999999-999);
        else if((k-1)/3 == 4) return  4*(n-999999999999)+3*(1000000000000-1000000000)+2*(1000000000-1000000)+1*(999999-999);
        else if((k-1)/3 == 5) return  5*(n-999999999999999)+4*(1000000000000000-999999999999)+3*(1000000000000-1000000000)+2*(1000000000-1000000)+1*(999999-999)-4;
        return n-999;
    }
};